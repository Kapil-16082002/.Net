✅🔥 Arithmetic operators are used to perform mathematical calculations on numeric data.

| Operator  | Name                | Syntax  | Small Example                           |
| --------- | ------------------- | ------- | --------------------------------------- |
| `+`       | Addition            | `a + b` | `Console.WriteLine(10 + 5); // 15`      |
| `-`       | Subtraction         | `a - b` | `Console.WriteLine(10 - 5); // 5`       |
| `*`       | Multiplication      | `a * b` | `Console.WriteLine(10 * 5); // 50`      |
| `/`       | Division            | `a / b` | `Console.WriteLine(10 / 3); // 3`       | Fractional part is discarded.
| `%`       | Modulus (Remainder) | `a % b` | `Console.WriteLine(10 % 3); // 1`       | Returns the remainder after division.
| `++`      | Pre Increment       | `++a`   | `int a=5; Console.WriteLine(++a); // 6` | First increments, then uses the value.
| `++`      | Post Increment      | `a++`   | `int a=5; Console.WriteLine(a++); // 5` | First uses the value, then increments.
| `--`      | Pre Decrement       | `--a`   | `int a=5; Console.WriteLine(--a); // 4` |
| `--`      | Post Decrement      | `a--`   | `int a=5; Console.WriteLine(a--); // 5` |
| Unary `+` | Positive Sign       | `+a`    | `int a=5; Console.WriteLine(+a); // 5`  | Represents a positive value.
| Unary `-` | Negation            | `-a`    | `int a=5; Console.WriteLine(-a); // -5` | Represents a negative value.
