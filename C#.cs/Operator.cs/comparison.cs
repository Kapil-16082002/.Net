✅🔥 Comparison operators (also called Relational Operators) are used to compare two values or expressions.

The result of every comparison operator is always a bool value:
true
false
These operators are commonly used with if, else, while, for, and other decision-making statements.

| **Operator** | **Meaning**              | **Expression** | **Small Code**                 |
| ------------ | ------------------------ | -------------- | ------------------------------ |
| `==`         | Equal to                 | `a == b`       | `Console.WriteLine(10 == 10);` |
| `!=`         | Not equal to             | `a != b`       | `Console.WriteLine(10 != 20);` |
| `>`          | Greater than             | `a > b`        | `Console.WriteLine(20 > 10);`  |
| `<`          | Less than                | `a < b`        | `Console.WriteLine(10 < 20);`  |
| `>=`         | Greater than or equal to | `a >= b`       | `Console.WriteLine(20 >= 20);` |
| `<=`         | Less than or equal to    | `a <= b`       | `Console.WriteLine(10 <= 20);` |
