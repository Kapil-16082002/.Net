✅🔥Program.cs
In ASP.NET Core, Program.cs is the application's entry point.
It is responsible for:
   Creating the application
   Starting the web server
   Registering services
   Building the request pipeline
Example:
var builder = WebApplication.CreateBuilder(args);
builder.Services.AddControllersWithViews();
var app = builder.Build();

// Building the Pipeline
app.UseHttpsRedirection(); 
app.UseStaticFiles(); 
app.UseRouting(); 
app.UseAuthentication();
app.UseAuthorization();
app.MapControllerRoute( // Maps incoming URLs to MVC controllers using the default route.
    name: "default",
    pattern: "{controller=Home}/{action=Index}/{id?}");
app.Run();
Key parts:
    builder.Services → Registers services used by the app (Dependency Injection).
    builder.Build() → Creates the WebApplication.
    app.Use...() → Adds middleware to the request pipeline.
    app.Map...() → Maps endpoints (such as MVC controllers).
    app.Run() → Starts listening for incoming HTTP requests.


=====================      Detailed Explanation        ==============================================================
// Creates a WebApplicationBuilder object.
// It initializes the ASP.NET Core application, loads configuration files
// (appsettings.json, environment variables, command-line arguments),
// sets up Dependency Injection (DI), Logging, and Configuration services.
var builder = WebApplication.CreateBuilder(args);

// ---------------------------
// Register Services
// ---------------------------

// Registers MVC services into the Dependency Injection (DI) container.
// This adds support for:
// • Controllers
// • Razor Views (.cshtml)
// • Model Binding
// • Model Validation
// • Action Filters
// • Routing
// • View Engine
// Without this line, the application cannot use the MVC pattern.
builder.Services.AddControllersWithViews();

// ---------------------------
// Build the Application
// ---------------------------

// Creates the WebApplication object.
// At this point, all registered services are finalized,
// and the application instance is ready to configure the HTTP request pipeline.
var app = builder.Build();

// ---------------------------
// Configure Middleware Pipeline
// ---------------------------

// Redirects all HTTP requests to HTTPS.
// Example:
// http://localhost:5000/Home/Index
//          ↓
// https://localhost:5001/Home/Index
// This improves application security by encrypting communication.
app.UseHttpsRedirection();

// Enables serving static files from the "wwwroot" folder.
// Static files include:
// • CSS
// • JavaScript
// • Images
// • Fonts
// • PDF files
// Requests for these files are served directly without reaching MVC.
app.UseStaticFiles();

// Adds the Routing Middleware.
// It analyzes the incoming URL and determines which endpoint
// (Controller + Action) should handle the request.
// Example:
// /Home/About
// Controller = Home
// Action = About
app.UseRouting();

// Adds Authentication Middleware.
// It checks whether the incoming request contains valid
// authentication credentials such as:
// • Cookie Authentication
// • JWT Token
// • OAuth
// If authentication succeeds, HttpContext.User is populated.
app.UseAuthentication();

// Adds Authorization Middleware.
// After the user is authenticated,
// this middleware checks whether the user has permission
// to access the requested resource.
// It evaluates:
// • Roles
// • Policies
// • Claims
// If authorization fails, the request is rejected.
app.UseAuthorization();

// Maps incoming URLs to MVC controllers using the default route.
//
// Route Template:
// {controller=Home}/{action=Index}/{id?}
//
// Meaning:
// controller -> Defaults to Home
// action     -> Defaults to Index
// id         -> Optional parameter
//
// Examples:
//
// URL: /
// Controller = Home
// Action = Index
//
// URL: /Home/About
// Controller = Home
// Action = About
//
// URL: /Product/Details/10
// Controller = Product
// Action = Details
// id = 10
app.MapControllerRoute(
    name: "default",
    pattern: "{controller=Home}/{action=Index}/{id?}");

// Starts the Kestrel web server.
// After this line executes:
// • The application begins listening for HTTP requests.
// • The configured middleware pipeline starts processing requests.
// • This is a blocking call—the application keeps running
//   until it is stopped (for example, Ctrl+C or application shutdown).
app.Run();



























