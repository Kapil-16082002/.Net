✅🔥 How a Request Flows Through ASP.NET Core
Browser // User enters a URL or clicks a link. The browser creates and sends an HTTP request to the server.
↓
HTTP GET /Home/Index // Example Request:HTTP GET /Home/Index. The browser sends an HTTP GET request asking for the Index action of the Home controller.
↓
Kestrel receives request // Kestrel is ASP.NET Core's built-in web server. It accepts the incoming HTTP request and hands it over to the ASP.NET Core application.
↓
Program.cs builds pipeline // Application Startup: The middleware pipeline defined in Program.cs is responsible for deciding how the request should be processed.
↓
Logging Middleware  // Middleware 1: Logs request information such as URL, HTTP method, execution time, and response status for monitoring and debugging.
↓
Exception Middleware // Middleware 2: Catches unhandled exceptions thrown later in the pipeline and generates an appropriate error response instead of crashing the application.
↓
Authentication Middleware // Middleware 3: Checks whether the request contains valid authentication credentials (Cookie, JWT Token, OAuth, etc.) and identifies the current user.
↓
Authorization Middleware // Middleware 4:  Verifies whether the authenticated user has permission to access the requested resource based on roles or policies.
↓
Routing Middleware  // Middleware 5: Matches the incoming URL (/Home/Index) with the appropriate controller and action using the application's routing configuration.
↓
MVC Controller // ASP.NET Core creates the appropriate controller object using Dependency Injection and prepares to execute the requested action.
↓
HomeController.Index() // The Index() action executes the application's business logic, retrieves data if necessary, and returns an ActionResult (usually a View).
↓
View // Razor View Engine: The Razor View Engine renders the corresponding .cshtml view by combining HTML with the data (Model) provided by the controller.
↓
HTML Response // The rendered HTML is packaged into an HTTP response and sent back through the middleware pipeline to Kestrel.
↓
Browser // Client: The browser receives the HTML response, parses it, loads CSS/JavaScript/images if needed, and displays the final web page to the user.


