✅🔥 What are Filters?
A Filter is a special component in ASP.NET Core MVC that allows you to execute code before or after different stages of MVC request processing.
Instead of writing the same code in every controller action, Filters let you write it once and reuse it across your application.

Microsoft designed Filters to handle cross-cutting concerns such as:
   Authentication
   Authorization
   Logging
   Validation
   Caching
   Exception Handling
   Auditing
   Performance Monitoring




























   