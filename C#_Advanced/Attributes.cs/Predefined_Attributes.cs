✅🔥Predefined Attributes in C#:
Predefined Attributes are built-in attributes provided by the .NET Framework and C# language. 
They are designed to provide common metadata that the compiler, CLR (Common Language Runtime), or .NET Framework can understand and use.


✅🔥 Why Do We Need Predefined Attributes?
Imagine if .NET did not provide built-in attributes.
If we wanted to:
  Mark a class as serializable
  Mark a method as obsolete
  Import a Windows API function
  Execute a method only in DEBUG mode
  Validate user input
We would have to create custom attributes every time.
To avoid this, .NET provides many ready-to-use attributes.


