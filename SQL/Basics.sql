✅ Database Management System (DBMS):
This software allows users to create and manage databases. 
It provides an interface for interacting with the database. 


✅ Table:
 A table is a collection of data organized in terms of rows and columns. Each table is provided with a name. 

✅ Column: 
A column (or field) is a set of data values of a particular type. 
For example, the column "Customer Name" in the "Customers" table will only contain names. 


✅ Row (Record or Tuple): 
A row represents a single record in a table. Each row contains a unique instance of data. 


✅ Primary key: 
This is a column or combination of columns that uniquely identifies a record in a table. 
Each table only includes one primary key. 


✅ Foreign key: 
This is one or more columns whose values are based on the primary key of another table. 
A foreign key helps to link tables together. 


✅ Index: 
This is a performance-tuning method of allowing faster retrieval of records. An index creates an entry for each value and hence faster to retrieve data

