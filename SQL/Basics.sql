✅🔥 1. What is SQL Server ?
SQL Server is a Relational Database Management System (RDBMS) developed by Microsoft that is used to store, manage, retrieve, and manipulate structured data using SQL (Structured Query Language).

In simple words:
SQL Server is software that stores data in tables and allows applications to perform operations like 
, inserting, updating, deleting, and retrieving data efficiently.

Example:
An e-commerce application stores:
    Customer information
    Product details
    Orders
    Payments
All this data can be stored and managed using SQL Server.


----------------------------------------------------------------

✅🔥 Why Do We Need SQL Server ?
Applications need a place to store data permanently.

For example:
A banking application needs to store Customer details like:
CustomerId
Name
AccountNumber
Balance

Without a database:
     Data is lost when the application closes.
     Searching data becomes difficult.
     Managing millions of records becomes impossible.
SQL Server provides:
✅ Data storage
✅ Data security
✅ Data consistency
✅ Fast searching
✅ Multiple user access
✅ Backup and recovery

